#!/usr/bin/env python3
"""Generate the launch-time reserved ranges from the build-time source reader."""
import argparse
from pathlib import Path
from patch_sites import sites


def render():
    lines = ['/* Generated by scripts/emit_botw_pchtxt_sites.py; do not edit the offsets by hand. */',
             '#pragma once', 'static const PchtxtSite g_pchtxt_reserved[] = {']
    for version, guard in [('botw190', '#ifdef GAME_BOTW190'), ('botw160', '#else')]:
        lines.append(guard)
        # The account GOT slot is a pointer, while the address reader reserves its instruction-sized first word.
        ranges = {(s.offset, s.size) for s in sites(version)}
        got = 0x1d78198 if version == 'botw190' else 0x2c7ef90
        ranges.discard((got, 4)); ranges.add((got, 8))
        lines.extend(f'    {{0x{offset:x}, 0x{size:x}}},' for offset, size in sorted(ranges))
    lines += ['#endif', '};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    text = render()
    if not args.out.exists() or args.out.read_text() != text:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
