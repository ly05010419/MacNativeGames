#!/usr/bin/env python3
"""Write the manifest.tsv of a player's RomFS mod (runtime/romfs.c loads it from TOTK_ROMFS_MODS, which the launcher sets to
~/Library/Application Support/MacNativeGames/TOTK/mods/<version>, or .../BotW/mods/botw160 or botw190 for Breath of the Wild).

The mod folder holds the replacement files under their RomFS paths (for example Sound/Resource/Stream/Dm_OP_0001.bwav).
A path the app replaces itself (its romfs-patches and the 2K romfs-patches-out overlays) is left out with a line
saying so: both overlays cannot be loaded, and for the heap table the line says whether the app's 2K overlay already
carries the mod's heap sizes (build_app.py chains them with --mod). --exclude leaves out further paths; Windows and macOS
droppings (desktop.ini, Thumbs.db, .DS_Store) are skipped.
Each line of the manifest names a path, the replacement's size and SHA-256 and the original's SHA-256; the game checks
all of them at start, so a mod made for another game version stops the start instead of loading. A file the RomFS lacks
is added (its original's SHA-256 is "-"), unless a RomFS path differs from it only in case: that is a misspelt
replacement (paths are case-sensitive), so nothing is written. The originals come
from the RomFS the app was built with: the app's Contents/Resources/totk/extracted/<version>/romfs (romfs.bin and
runtime-index.bin), or a build work folder's extracted/<version>/romfs.

A mod file the build's own RomFS overlay also replaces (extracted/<version>/romfs-patches, scripts/make_romfs_patches.py)
would stop the start, since two overlays may not replace one file. Translations replace the UI archive
Common.Product.<n>.Nin_NX_NVN.blarc.zs for its textures with words, and the build moves the quick-menu capture keys in
the same archive (issue #73). So the build's edit is applied to the mod's archive with the same checks as
make_romfs_patches.py: the mod must not have changed the members the build patches, and the result must hold exactly
the build's patched members. The merged archive takes the mod file's place (the mod's own file is kept next to it as
<name>.mod-original, and used again on the next run), and its line names the SHA-256 of the build's patched file as the
original: runtime/romfs.c then lets it replace the build's overlay. Any other collision still stops the start. --check
writes nothing, so it reports what it would merge and leaves the merging to the run that writes.

usage: make_mod_manifest.py <mod folder> (--app <Tears of the Kingdom.app | Breath of the Wild.app> | --romfs <folder>) [--version v143 | botw190]
                              [--exclude <RomFS path or glob>]... [--check]
"""
import argparse
from collections import namedtuple
import fnmatch
import hashlib
from pathlib import Path
import struct
import sys

VERSIONS = ('v0', 'v112', 'v121', 'v143')
APP_VERSIONS = VERSIONS + ('botw160', 'botw190')   # the folders an app's RomFS can sit in (VERSIONS: Tears of the Kingdom only)
CHUNK = 8 << 20
# Windows/macOS droppings that mod managers (TKMM, Ryujinx output folders) leave in a RomFS tree: never a game file.
JUNK = {'desktop.ini', 'thumbs.db', '.ds_store'}
MANIFEST_HEADER = '# path\tsize\tsha256\toriginal_sha256 (generated by scripts/make_mod_manifest.py)\n'
KEPT = '.mod-original'   # the mod's own copy of a file merged with the build's patch (never a game file)
IMAGE_DIR = None   # the folder of romfs.bin when it is not beside the index: --romfs-data, or an app built with --mac-game-data library


def image_file(romfs):
    return (IMAGE_DIR or romfs)/'romfs.bin'


def app_image_dir(app, version):
    """The folder of the RomFS image of an app built with --mac-game-data library, found as app/launcher.m finds it: the
    folder the player chose when the app asked (defaults MNGGameDataFolder.<version>), the folder the build was given
    (Info.plist MNGGameDataFolder), else the data folder's GameData; romfs.bin in <folder>/<version> or in the folder."""
    import plistlib, subprocess
    try:
        info = plistlib.loads((app/'Contents/Info.plist').read_bytes())
    except (OSError, ValueError):
        info = {}
    chosen = subprocess.run(['defaults', 'read', info['CFBundleIdentifier'], f'MNGGameDataFolder.{version}'], capture_output=True,
                            text=True).stdout.strip() if info.get('CFBundleIdentifier') else ''
    game = 'BotW' if version.startswith('botw') else 'TOTK'
    folders = [Path(f) for f in (chosen, info.get('MNGGameDataFolder')) if f]
    folders.append(Path.home()/f'Library/Application Support/MacNativeGames/{game}/GameData')
    places = [place for folder in folders for place in (folder/version, folder)]
    return next((place for place in places if (place/'romfs.bin').is_file()), places[0])

# What manifest() finds in a mod folder, read by name: a caller that only needs the lines does not break when a field is
# added, and a caller can leave the writing to write_manifest().
Manifest = namedtuple('Manifest', 'lines same added misspelt excluded taken')
Manifest.__doc__ = """The manifest of one mod folder.

    lines      the manifest.tsv lines, one per path the mod replaces or adds
    same       paths left out because the mod's file is byte-identical to the original
    added      paths the RomFS does not have (the new files the mod brings)
    misspelt   (mod path, the RomFS path that differs only in case) pairs
    excluded   paths left out by an --exclude pattern
    taken      path -> the app's own replacement of it, for paths the app replaces itself"""


def read_index(path):
    """RomFS path -> (offset, size) from runtime-index.bin (scripts/prepare_romfs_backend.py writes it)."""
    data = path.read_bytes()
    magic, count, strings = struct.unpack_from('<8sQQ', data, 0)
    if magic != b'TOTKRFS1' or strings != 24 + count*24 or strings > len(data):
        raise ValueError(f'{path}: not a RomFS index')
    files = {}
    for i in range(count):
        offset, size, name, length = struct.unpack_from('<QQII', data, 24 + i*24)
        files[data[strings+name:strings+name+length-1].decode()] = (offset, size)
    return files


def sha256_range(handle, offset, size):
    digest = hashlib.sha256()
    handle.seek(offset)
    while size:
        block = handle.read(min(CHUNK, size))
        if not block:
            raise ValueError('RomFS image ends early')
        digest.update(block)
        size -= len(block)
    return digest.hexdigest()


HEAPDEF = 'System/HeapSize/Product.Nin_NX_NVN.HeapDef.byml.zs'


def app_overlays(app, version):
    """RomFS path -> the app's own replacement of it (extracted/<version>/romfs-patches*, the 2K HeapDef included). The
    game stops at the first start when a mod replaces one of them too (runtime/romfs.c), so the manifest leaves every one
    of them to the app."""
    root = app/'Contents/Resources/totk/extracted'/version
    replaced = {}
    manifests = [root/'romfs-patches/manifest.tsv', *sorted((root/'romfs-patches-out').glob('*/manifest.tsv'))]
    for path in manifests:
        if path.is_file():
            for line in path.read_text().splitlines():
                name = line.split('\t', 1)[0]
                if name and not name.startswith('#'):
                    replaced.setdefault(name, path.parent/name)
    return replaced


TWO_K = ('DynamicTextureAllocatorMem', 'Graphics')     # the two heaps scripts/make_output_res_overlay.py grows


def heap_sizes(byml):
    """System/HeapSize/Product.Nin_NX_NVN.HeapDef.byml (BYML v7, "YB") -> {heap name: Size in KiB}."""
    assert byml[:2] == b'YB' and struct.unpack_from('<H', byml, 2)[0] == 7
    keys_at, _, root = struct.unpack_from('<III', byml, 4)
    count = struct.unpack_from('<I', byml, keys_at)[0] >> 8
    offsets = struct.unpack_from(f'<{count + 1}I', byml, keys_at + 4)
    keys = [byml[keys_at + o: byml.index(0, keys_at + o)].decode() for o in offsets[:count]]
    def entry(node, name):
        """The value field of hash node `node`'s entry `name`."""
        assert byml[node] == 0xc1, 'not a hash node'
        for i in range(struct.unpack_from('<I', byml, node)[0] >> 8):
            at = node + 4 + 8*i
            if keys[struct.unpack_from('<I', byml, at)[0] & 0xffffff] == name:
                return at + 4, byml[at + 3]
        raise KeyError(name)
    heaps = struct.unpack_from('<I', byml, entry(root, 'Heaps')[0])[0]
    sizes = {}
    for i in range(struct.unpack_from('<I', byml, heaps)[0] >> 8):
        at = heaps + 4 + 8*i
        name = keys[struct.unpack_from('<I', byml, at)[0] & 0xffffff]
        node = struct.unpack_from('<I', byml, at + 4)[0]
        try:
            field, kind = entry(node, 'Size')
            if kind == 0xd1:
                sizes[name] = struct.unpack_from('<i', byml, field)[0]
        except (KeyError, AssertionError):
            pass
    return sizes


def heapdef_carried(mod_file, app_file):
    """True when the app's 2K overlay keeps this mod's heap sizes (the build chains the table with --mod: every heap
    equal, and the two 2K heaps grown by the same amount), False when it does not, None when that cannot be told here
    (no zstd module, or unreadable files)."""
    try:
        from compression import zstd
    except ImportError:
        return None
    try:
        mod, app = heap_sizes(zstd.decompress(mod_file.read_bytes())), heap_sizes(zstd.decompress(app_file.read_bytes()))
    except (zstd.ZstdError, OSError, ValueError, AssertionError, struct.error):
        return None
    if set(mod) != set(app):
        return False
    extra = {name: app[name] - mod[name] for name in mod if app[name] != mod[name]}
    if any(name not in TWO_K for name in extra):
        return False
    return not extra or (len(extra) == len(TWO_K) and len(set(extra.values())) == 1 and next(iter(extra.values())) > 0)


def manifest(mod, romfs, excludes=(), app_replaced=None, merged=None):
    """The manifest lines for every file in the mod folder; files equal to their original are left out, anything matching
    an --exclude pattern is left out, and so is a path the app replaces itself (app_replaced: path -> the app's file).
    `merged` maps a path merged with the build's own patch to the SHA-256 of the build's file, which its line names as the
    original, so the game lets it replace the build's overlay. Returns a Manifest record: misspelt pairs a mod path with
    the RomFS path that differs only in case; taken maps a left-out path to the app's own replacement of it."""
    index = read_index(romfs/'runtime-index.bin')
    folded = {name.lower(): name for name in index}
    app_replaced = app_replaced or {}
    merged = merged or {}
    lines, same, added, misspelt, excluded, taken = [], [], [], [], [], {}
    with image_file(romfs).open('rb') as image:
        for file in sorted(p for p in mod.rglob('*') if p.is_file()):
            name = file.relative_to(mod).as_posix()
            if name == 'manifest.tsv' or name.endswith(KEPT) or any(part.startswith('.') for part in file.relative_to(mod).parts):
                continue
            if file.name.lower() in JUNK:
                continue
            if any(fnmatch.fnmatchcase(name, pattern) for pattern in excludes):
                excluded.append(name)
                continue
            if name in merged:                       # merged with the build's patch: it takes the overlay's place
                with file.open('rb') as handle:
                    lines.append(f'{name}\t{file.stat().st_size}\t'
                                 f'{sha256_range(handle, 0, file.stat().st_size)}\t{merged[name]}')
                continue
            if name in app_replaced:                 # the app's own overlay replaces it: both cannot be loaded
                taken[name] = file
                continue
            if name not in index:
                if name.lower() in folded:
                    misspelt.append((name, folded[name.lower()]))
                    continue
                with file.open('rb') as handle:
                    lines.append(f'{name}\t{file.stat().st_size}\t{sha256_range(handle, 0, file.stat().st_size)}\t-')
                added.append(name)
                continue
            offset, size = index[name]
            with file.open('rb') as handle:
                replacement = sha256_range(handle, 0, file.stat().st_size)
            original = sha256_range(image, offset, size)
            if replacement == original:
                same.append(name)
                continue
            lines.append(f'{name}\t{file.stat().st_size}\t{replacement}\t{original}')
    return Manifest(lines, same, added, misspelt, excluded, taken)


def manifest_text(found):
    """The bytes of a manifest.tsv for a Manifest record (its header included)."""
    return MANIFEST_HEADER + '\n'.join(found.lines) + '\n'


def write_manifest(mod, romfs, excludes=(), app_replaced=None, merged=None):
    """Write <mod>/manifest.tsv and return what was found (Manifest). Nothing is written when a path is misspelt: the
    caller names the paths, so a mod is never given a manifest that stops the game at start. Tools that write a mod's
    manifest (this script, make_button_icons.py) go through here, so each one reads the record by name."""
    found = manifest(mod, romfs, excludes, app_replaced, merged)
    if not found.misspelt:
        (mod/'manifest.tsv').write_text(manifest_text(found))
    return found


def build_patches(romfs):
    """The build's own RomFS overlay next to this RomFS (extracted/<version>/romfs-patches): its folder and path -> SHA-256."""
    folder = romfs.parent/'romfs-patches'
    patches = {}
    if (folder/'manifest.tsv').is_file():
        for line in (folder/'manifest.tsv').read_text().splitlines():
            if line and not line.startswith('#'):
                path, _, sha, _ = line.split('\t')
                patches[path] = sha
    return folder, patches


def merge_build_patches(mod, romfs, index):
    """Merge each mod file the build's own overlay also replaces with the build's edit (merge_build_patch): path -> the
    SHA-256 of the build's file, the `merged` of manifest() and write_manifest(). Raises ValueError when one can't be
    merged. Tools that write a mod's files (this script, make_button_icons.py) call it before writing the manifest."""
    folder, patches = build_patches(romfs)
    merged = {}
    for name, build_sha in patches.items():
        if name in index and ((mod/name).is_file() or (mod/(name + KEPT)).is_file()) and \
                merge_build_patch(mod, name, romfs, index, folder, build_sha):
            merged[name] = build_sha
    return merged


def changes_original(name, mod, romfs, index):
    """Whether the mod's own copy of `name` differs from the RomFS original - true when a merge would change something.
    Read-only, for --check: it says what would be merged without writing the merged archive."""
    file = mod/(name + KEPT) if (mod/(name + KEPT)).is_file() else mod/name
    if name not in index:
        return True
    offset, size = index[name]
    with image_file(romfs).open('rb') as image, file.open('rb') as handle:
        return sha256_range(handle, 0, file.stat().st_size) != sha256_range(image, offset, size)


def merge_build_patch(mod, name, romfs, index, folder, build_sha):
    """Apply the build's edit (make_romfs_patches.py) to the mod's copy of the UI archive `name` and write the result in its
    place; the mod's own file is kept as <name>.mod-original. False when the mod's file is the original (nothing to merge);
    raises ValueError when the two can't be merged."""
    target, kept = mod/name, mod/(name + KEPT)
    if name not in index:      # the build adds this file rather than replacing one: nothing to merge with
        return False
    if target.is_file() and not kept.is_file():
        offset, size = index[name]
        with image_file(romfs).open('rb') as image, target.open('rb') as handle:
            if sha256_range(handle, 0, target.stat().st_size) == sha256_range(image, offset, size):
                return False   # the original itself: the manifest leaves it out
    try:
        import compression.zstd as zstd   # Python 3.14
    except ImportError:
        raise ValueError(f'{name}: merging it with the build\'s patch needs Python 3.14 (compression.zstd)') from None
    from make_romfs_patches import MEMBERS, common_archive, patch_capture, sarc_members
    if name not in {common_archive(v) for v in VERSIONS}:
        raise ValueError(f'{name}: the build patches this file too, and only the UI archive Common.Product.<n> can be merged; '
                         'leave it out of the mod')
    build_raw = (folder/name).read_bytes()
    if hashlib.sha256(build_raw).hexdigest() != build_sha:
        raise ValueError(f'{folder/name} does not match the build\'s manifest')
    with image_file(romfs).open('rb') as image:
        def read(path):
            offset, size = index[path]; image.seek(offset); data = image.read(size); assert len(data) == size; return data
        pack = zstd.decompress(read('Pack/ZsDic.pack.zs'))
        original_raw = read(name)
    dictionaries = {}
    for lo, hi in sarc_members(pack).values():
        d = zstd.ZstdDict(pack[lo:hi]); dictionaries[d.dict_id] = d
    def unpack(raw):
        info = zstd.get_frame_info(raw)
        if info.dictionary_id and info.dictionary_id not in dictionaries:
            raise ValueError(f'{name}: compressed with a zstd dictionary the game does not have')
        return bytearray(zstd.decompress(raw, zstd_dict=dictionaries[info.dictionary_id]) if info.dictionary_id else zstd.decompress(raw))
    original, build = unpack(original_raw), unpack(build_raw)
    om, bm = sarc_members(original), sarc_members(build)
    if any(original[slice(*om[k])] != build[slice(*bm[k])] for k in om if k not in MEMBERS) or om.keys() != bm.keys():
        raise ValueError(f'{name}: the build\'s patch changes more than {", ".join(MEMBERS)}; this tool merges only those')
    if target.is_file():   # the mod's own file, unless it is an earlier merge (it holds the build's edit) and the copy is kept
        candidate = unpack(target.read_bytes()); cm = sarc_members(candidate)
        if not kept.is_file() or not all(k in cm and candidate[slice(*cm[k])] == build[slice(*bm[k])] for k in MEMBERS):
            target.replace(kept)
    if not kept.is_file():
        raise ValueError(f'{name}: {kept.name} is missing, so the mod\'s own archive is unknown; copy the mod\'s file in again')
    blarc = unpack(kept.read_bytes()); members = sarc_members(blarc)
    for k in MEMBERS:
        if k not in members or blarc[slice(*members[k])] != original[slice(*om[k])]:
            raise ValueError(f'{name}: the mod changes {k}, which the build patches too, so the two can\'t be merged')
    patch_capture(blarc, members, 0.0)
    for k in MEMBERS:
        if blarc[slice(*members[k])] != build[slice(*bm[k])]:
            raise ValueError(f'{name}: after the edit, {k} differs from the build\'s (another capture frame?); not merged')
    dictionary = zstd.get_frame_info(build_raw).dictionary_id
    data = zstd.compress(bytes(blarc), level=19, zstd_dict=dictionaries[dictionary]) if dictionary else zstd.compress(bytes(blarc), level=19)
    if unpack(data) != blarc:
        raise ValueError(f'{name}: the merged archive does not decompress to itself')
    target.write_bytes(data)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('mod', type=Path, help='the mod folder, files under their RomFS paths')
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--app', type=Path, help='the built Tears of the Kingdom.app or Breath of the Wild.app')
    source.add_argument('--romfs', type=Path, help='a folder holding romfs.bin and runtime-index.bin')
    parser.add_argument('--romfs-data', type=Path, help='the folder holding romfs.bin when it is not beside the index (an app '
                        'built with --mac-game-data library: <data>/GameData/<version>; with --app that folder is the default)')
    parser.add_argument('--version', choices=APP_VERSIONS, help='the game version (default: the mod folder name)')
    parser.add_argument('--exclude', action='append', default=[], metavar='PATH',
                        help='a RomFS path or glob to leave out of the manifest as well (files the app replaces itself '
                             'are left out without it)')
    parser.add_argument('--check', action='store_true',
                        help='check the folder and say what the manifest would hold; write nothing (build_app.py runs '
                             'this before it replaces a player\'s mod folder)')
    args = parser.parse_args()
    version = args.version or (args.mod.resolve().name if args.mod.resolve().name in APP_VERSIONS else None)
    romfs = args.romfs
    if args.app:
        if not version:
            parser.error('name the game version with --version (or name the mod folder v0, v112, v121, v143, botw160 or botw190)')
        romfs = args.app/f'Contents/Resources/totk/extracted/{version}/romfs'
    global IMAGE_DIR
    IMAGE_DIR = args.romfs_data
    if args.app and not args.romfs_data and not (romfs/'romfs.bin').exists():   # built with --mac-game-data library
        IMAGE_DIR = app_image_dir(args.app, version)
    for need in (image_file(romfs), romfs/'runtime-index.bin'):
        if not need.is_file():
            parser.error(f'{need} not found')
    if not args.mod.is_dir():
        parser.error(f'{args.mod} is not a folder')
    replaced = app_overlays(args.app, version) if args.app else {}
    # A file the build's own overlay replaces is merged with the build's edit rather than left out (issue #73). --check
    # writes nothing, so there it only says what it would merge, and counts the file as one the mod changes.
    index = read_index(romfs/'runtime-index.bin')
    if args.check:
        merged = {}
        for name, build_sha in build_patches(romfs)[1].items():
            if name in index and ((args.mod/name).is_file() or (args.mod/(name + KEPT)).is_file()) and \
                    changes_original(name, args.mod, romfs, index):
                merged[name] = build_sha
                print(f'would merge with the build\'s patch: {name} (nothing written: --check)')
    else:
        try:
            merged = merge_build_patches(args.mod, romfs, index)
        except ValueError as error:
            sys.exit(f'nothing written: {error}')
        for name in merged:
            print(f'merged with the build\'s patch: {name} (the mod\'s own file: {name}{KEPT})')
    found = manifest(args.mod, romfs, args.exclude, replaced, merged)
    for name in found.same:
        print(f'left out (same as the original): {name}')
    for name in found.excluded:
        print(f'left out (--exclude): {name}')
    for name, file in sorted(found.taken.items()):
        where = replaced[name].relative_to(args.app).as_posix()
        if name == HEAPDEF:
            carried = heapdef_carried(file, replaced[name])
            if carried:
                print(f'left out (the app replaces it, and the 2K overlay already carries these heap sizes): {name}')
            elif carried is False:
                print(f'left out (the app replaces it, but with other heap sizes: rebuild the app with --mod pointing '
                      f'at this mod to keep them): {name}')
            else:
                print(f'left out (the app replaces it; build with --mod pointing at this mod to keep its heap sizes): {name}')
        else:
            print(f'left out (the app replaces it too, so this file would not be used: {where}): {name}')
    if found.misspelt:
        for name, real in found.misspelt:
            print(f'not a file of this RomFS: {name} (it has {real}; paths are case-sensitive)', file=sys.stderr)
        sys.exit('nothing written: rename the files above')
    if found.added:
        print(f'{len(found.added)} files the RomFS lacks are added, for example {found.added[0]}')
    if not found.lines:
        if args.check:
            print('the folder replaces or adds no file: that is not an error here, only --check')
            return
        sys.exit('nothing written: the folder replaces or adds no file')
    if args.check:
        print(f'--check: nothing written; the manifest would hold {len(found.lines)} files '
              f'({len(found.lines) - len(found.added)} replaced, {len(found.added)} added)')
        return
    (args.mod/'manifest.tsv').write_text(manifest_text(found))
    print(f'{args.mod/"manifest.tsv"}: {len(found.lines)} files ({len(found.lines) - len(found.added)} replaced, {len(found.added)} added)')


if __name__ == '__main__':
    main()
