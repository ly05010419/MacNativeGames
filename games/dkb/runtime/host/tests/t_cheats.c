    CHECK(rd32(0x4600) == 1 && rd32(0x4604) == 0 && rd32(0x4608) == 0xFE && rd32(0x4698) == 0x234A, "9: add at width 4 and sub at width 1 truncate the result; a narrow immediate is the word's low bytes");
